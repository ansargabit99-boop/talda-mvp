class Con:
    """Thin wrapper so the same SQL (with ? placeholders) runs on SQLite and Postgres."""

    def __init__(self, raw):
        self.raw = raw

    def execute(self, sql: str, params=()):
        return self.raw.execute(sql.replace("?", "%s") if IS_PG else sql, params)

    def insert_responses(self, rows: list[tuple]) -> None:
        if IS_PG:
            with self.raw.cursor() as cur, cur.copy(
                    "COPY responses(upload_id,school_id,student_id,topic_id,topic_hours,item_id,option) FROM STDIN") as cp:
                for r in rows:
                    cp.write_row(r)
        else:
            self.raw.executemany("INSERT INTO responses VALUES(?,?,?,?,?,?,?)", rows)


@contextmanager
def db():
    if IS_PG:
        import psycopg
        from psycopg.rows import dict_row
        raw = psycopg.connect(PG_URL, row_factory=dict_row)
    else:
        raw = sqlite3.connect(DB_PATH)
        raw.row_factory = sqlite3.Row
        raw.execute("PRAGMA foreign_keys=ON")
    try:
        yield Con(raw)
        raw.commit()
    except BaseException:
        raw.rollback()
        raise
    finally:
        raw.close()


def hash_pw(password: str, salt: str) -> str:
    return hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), 200_000).hex()


def create_user(con, login: str, name: str, password: str, role: str, school_id: str | None = None) -> None:
    salt = secrets.token_hex(16)
    con.execute("INSERT INTO users(login,name,salt,pw_hash,role,school_id) VALUES(?,?,?,?,?,?)",
                (login, name, salt, hash_pw(password, salt), role, school_id))


