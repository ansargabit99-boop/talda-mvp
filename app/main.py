@app.post("/api/items")
def save_item(data: ItemIn, talda_session: str | None = Cookie(None)):
    u = current_user(talda_session)
    if len(data.options) != 4 or len(data.mapping) != 4 or not 0 <= data.correct <= 3:
        raise HTTPException(400, "Нужно ровно 4 варианта ответа")
    if not re.fullmatch(r"[A-Za-z]+\d+", data.topic_id):
        raise HTTPException(400, "Неверный код темы")
    mapping = [0 if i == data.correct else max(1, min(3, m)) for i, m in enumerate(data.mapping)]
