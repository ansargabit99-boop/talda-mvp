    s_idx = {s["id"]: i for i, s in enumerate(schools)}
    for s in schools:
        s["hours"] = json.loads(s["hours"] or "{}")
    students, st_idx, items, it_idx, flat = [], {}, [], {}, []
    for r in resp:
        key = (r["school_id"], r["student_id"])
        if key not in st_idx:
            st_idx[key] = len(students)
            students.append([f"{r['school_id']}/{r['student_id']}", s_idx[r["school_id"]]])
        if r["item_id"] not in it_idx:
            it_idx[r["item_id"]] = len(items)
            items.append(r["item_id"])
        flat += (st_idx[key], it_idx[r["item_id"]], r["option"])
    return {"schools": schools, "students": students, "items": items, "r": flat}

