def current_user(token: str | None):
    if not token:
        raise HTTPException(401, "Нужно войти")
    with db() as con:
        row = con.execute("SELECT u.* FROM sessions s JOIN users u ON u.id=s.user_id WHERE s.token=? AND s.created>?",
                          (token, time.time() - SESSION_DAYS * 86400)).fetchone()
    if not row:
        raise HTTPException(401, "Сессия истекла, войдите снова")
    return dict(row)


