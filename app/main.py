@app.post("/api/login")
def login(data: LoginIn, response: Response):
    with db() as con:
        u = con.execute("SELECT * FROM users WHERE login=?", (data.login.strip(),)).fetchone()
        if not u or not hmac.compare_digest(u["pw_hash"], hash_pw(data.password, u["salt"])):
            raise HTTPException(401, "Неверный логин или пароль")
        token = secrets.token_urlsafe(32)
        con.execute("INSERT INTO sessions VALUES(?,?,?)", (token, u["id"], time.time()))
    response.set_cookie("talda_session", token, httponly=True, samesite="lax", secure=ON_VERCEL, max_age=SESSION_DAYS * 86400)
    return {"ok": True}


