def gemini(prompt: str, json_mode: bool = False) -> str:
    key = os.getenv("GEMINI_API_KEY")
    if not key:
        raise HTTPException(503, "ИИ выключен: добавьте GEMINI_API_KEY в настройки сервера и перезапустите")
    body = {"contents": [{"role": "user", "parts": [{"text": prompt}]}], "generationConfig": {"temperature": 0.3}}
    if json_mode:
        body["generationConfig"]["responseMimeType"] = "application/json"
    req = urllib.request.Request(
        f"https://generativelanguage.googleapis.com/v1beta/models/{GEMINI_MODEL}:generateContent",
        data=json.dumps(body).encode(), headers={"Content-Type": "application/json", "x-goog-api-key": key})
    try:
        with urllib.request.urlopen(req, timeout=55) as r:
            data = json.load(r)
    except urllib.error.HTTPError as e:
        raise HTTPException(502, f"Gemini вернул ошибку {e.code}: {e.read().decode(errors='replace')[:300]}")
    except urllib.error.URLError as e:
        raise HTTPException(502, f"Нет связи с Gemini: {e.reason}")
    try:
        return "".join(p.get("text", "") for p in data["candidates"][0]["content"]["parts"])
    except (KeyError, IndexError):
        raise HTTPException(502, "Gemini не вернул ответ (возможно, сработал фильтр безопасности)")


