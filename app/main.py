def read_table(name: str, raw: bytes) -> list[list[str]]:
    if name.lower().endswith((".xlsx", ".xlsm")):
        from openpyxl import load_workbook
        ws = load_workbook(io.BytesIO(raw), read_only=True, data_only=True).active
        return [["" if v is None else str(v).strip() for v in row] for row in ws.iter_rows(values_only=True)]
    text = raw.decode("utf-8-sig", errors="replace")
    try:
        dialect = csv.Sniffer().sniff(text[:4096], delimiters=",;\t")
    except csv.Error:
        dialect = csv.excel
    return [[c.strip() for c in row] for row in csv.reader(io.StringIO(text), dialect)]


def option_code(value: str, item_id: str, bank: dict) -> int:
    v = value.strip().upper()
    if v in ("0", "1", "2", "3"):
        return int(v)
    letters = {"A": 0, "B": 1, "C": 2, "D": 3, "А": 0, "Б": 1, "В": 2, "Г": 3}
    if v in letters:
        # Bank items map letters via their tagging; base items T*.1–3 use A = correct, B–D = misconceptions 1–3.
        return bank[item_id][letters[v]] if item_id in bank else letters[v]
    raise ValueError(f"ответ «{value}» для задания {item_id}: ожидается буква A–D или код 0–3")


def topic_of(item: str) -> str:
    return item.split(".")[0]


@app.post("/api/upload")
async def upload(file: UploadFile = File(...), talda_session: str | None = Cookie(None)):
    u = current_user(talda_session)
    name = file.filename or "upload.csv"
    raw = await file.read()
    if name.lower().endswith(".gz"):
        try:
            raw = gzip.decompress(raw)
        except OSError:
            raise HTTPException(400, "Повреждённый архив .gz")
        name = name[:-3]
    if len(raw) > MAX_UPLOAD:
        raise HTTPException(413, "Файл больше 40 МБ")
    try:
        table = [r for r in read_table(name, raw) if any(r)]
    except Exception as e:  # noqa: BLE001
        raise HTTPException(400, f"Не удалось прочитать файл: {e}")
    if len(table) < 2:
        raise HTTPException(400, "В файле нет строк с данными")
    head = [h.lower() for h in table[0]]
    with db() as con:
        bank = {r["id"]: json.loads(r["mapping"]) for r in con.execute("SELECT id, mapping FROM items").fetchall()}
        rows, new_schools = [], {}
        try:
            if all(c in head for c in FULL_COLS):  # full regional format
                require_method(u)
                ix = {c: head.index(c) for c in FULL_COLS}
                for r in table[1:]:
                    g = lambda c: r[ix[c]] if ix[c] < len(r) else ""  # noqa: E731
                    sid, item = g("school_id"), g("item_id")
                    if not sid or not item:
                        continue
                    if sid not in new_schools:
                        new_schools[sid] = (sid, sid, g("district") or "—", "urban" if g("area") == "urban" else "rural",
                                            1 if g("small") == "1" else 0, "ru" if g("lang") == "ru" else "kz",
                                            (g("textbook") or "A").upper(), int(float(g("prev_score") or 50)))
                    t = g("topic_id") or topic_of(item)
                    rows.append((sid, g("student_id"), t, int(float(g("topic_hours") or PROGRAM_HOURS.get(t, 8))), item, option_code(g("option"), item, bank)))
            else:  # school format: long (student_id,item_id,option) or wide (student_id + a column per item)
                school_id = u["school_id"]
                if not school_id:
                    raise HTTPException(400, "Методист загружает файл в полном формате (с колонкой school_id). Учитель — в формате своей школы.")
                school = con.execute("SELECT hours FROM schools WHERE id=?", (school_id,)).fetchone()
                hours = json.loads(school["hours"] or "{}")
                if "student_id" not in head:
                    raise HTTPException(400, "Нужна колонка student_id")
                si = head.index("student_id")
                if "item_id" in head and "option" in head:
                    ii, oi = head.index("item_id"), head.index("option")
                    hi = head.index("topic_hours") if "topic_hours" in head else None
                    for r in table[1:]:
                        item = r[ii]
                        t = topic_of(item)
                        h = int(float(r[hi])) if hi is not None and r[hi] else hours.get(t, PROGRAM_HOURS.get(t, 8))
                        rows.append((school_id, r[si], t, h, item, option_code(r[oi], item, bank)))
                else:
                    item_cols = [(j, table[0][j]) for j in range(len(head)) if j != si and re.fullmatch(r"[A-Za-z]+\d+\.\d+", table[0][j])]
                    if not item_cols:
                        raise HTTPException(400, "Не найдены колонки заданий вида T9.1, T9.2 …")
                    for r in table[1:]:
                        for j, item in item_cols:
                            if j < len(r) and r[j] != "":
                                t = topic_of(item)
                                rows.append((school_id, r[si], t, hours.get(t, PROGRAM_HOURS.get(t, 8)), item, option_code(r[j], item, bank)))
        except ValueError as e:
            raise HTTPException(400, f"Ошибка в данных: {e}")
        if not rows:
            raise HTTPException(400, "Не найдено ни одного ответа")
        for s in new_schools.values():
            con.execute("""INSERT INTO schools(id,name,district,area,small,lang,textbook,prev_score) VALUES(?,?,?,?,?,?,?,?)
                           ON CONFLICT(id) DO NOTHING""", s)
        hours_by_school: dict = {}
        for sid, _, t, h, _, _ in rows:
            hours_by_school.setdefault(sid, {})[t] = h
        for sid, hs in hours_by_school.items():
            cur = con.execute("SELECT hours FROM schools WHERE id=?", (sid,)).fetchone()
            con.execute("UPDATE schools SET hours=? WHERE id=?", (json.dumps({**json.loads(cur["hours"] or "{}"), **hs}), sid))
        n_students, n_schools = len({(r[0], r[1]) for r in rows}), len({r[0] for r in rows})
        uid = con.execute("INSERT INTO uploads(user_id,filename,n_rows,students,schools,is_demo,created) VALUES(?,?,?,?,?,?,?) RETURNING id",
                          (u["id"], name, len(rows), n_students, n_schools, 1 if name.startswith("demo-") else 0, time.time())).fetchone()["id"]
        con.insert_responses([(uid, *r) for r in rows])
    return {"ok": True, "upload_id": uid, "rows": len(rows), "students": n_students, "schools": n_schools}


